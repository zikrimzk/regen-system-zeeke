    public static function language(): string
    {
        $choice = $_GET['lang'] ?? null;
        if (in_array($choice, ['en', 'ms'], true)) return $choice;
        return ($_COOKIE['regen_language'] ?? '') === 'ms' ? 'ms' : 'en';
    }

    public static function applyPreference(): void
    {
        $choice = $_GET['lang'] ?? null;
        if (!in_array($choice, ['en', 'ms'], true)) return;
        setcookie('regen_language', $choice, ['path'=>'/', 'secure'=>Http::isHttps(), 'httponly'=>true, 'samesite'=>'Lax']);
    }

    public static function text(string $key): string
    {
        return (PublicProductCopy::TEXT[$key] ?? self::TEXT[$key])[self::language() === 'ms' ? 1 : 0] ?? throw new \LogicException('Missing UI text: ' . $key);
    }

    public static function html(string $key): string
    {
        return htmlspecialchars(self::text($key), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }

    public static function dictionary(bool $commercial = false): string
    {
        $index = self::language() === 'ms' ? 1 : 0;
        return json_encode(array_map(static fn(array $pair): string => $pair[$index], ($commercial ? self::TEXT + PublicProductCopy::TEXT : self::TEXT)),
            JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_THROW_ON_ERROR);
    }

    public static function languageLink(string $class = '', string $role = ''): string
    {
        // Keep document and navigation state during an explicit language switch.
        $query = $_GET;
        $malay = self::language() === 'ms';
        $locale = $malay ? 'en' : 'ms';
        $query['lang'] = $locale;
        $path = Http::path();
        if (!str_starts_with($path, '/') || str_starts_with($path, '//') || str_contains($path, '\\')) $path = '/';
        $href = htmlspecialchars($path . '?' . http_build_query($query, '', '&', PHP_QUERY_RFC3986), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
        return '<a class="language-link ' . $class . '" href="' . $href . '" hreflang="' . $locale . '" lang="' . $locale
            . '" data-language-switch ' . ($role === 'menuitem' ? 'role="menuitem" ' : '') . 'aria-label="'
            . self::html($malay ? 'common.toEnglish' : 'common.toMalay') . '">' . ($malay ? 'EN' : 'BM') . '</a>';
    }
